package com.voidos.launcher;

import android.app.Activity;
import android.content.Context;
import android.content.Intent;
import android.content.SharedPreferences;
import android.content.pm.PackageManager;
import android.content.pm.ResolveInfo;
import android.os.Bundle;
import android.view.View;
import android.view.ViewGroup;
import android.widget.ArrayAdapter;
import android.widget.CheckBox;
import android.widget.ListView;
import android.widget.TextView;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

public class PrivacySettingsActivity extends Activity {

    private SharedPreferences sharedPreferences;
    private Set<String> hiddenAppsSet;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        setContentView(R.layout.activity_privacy_settings);

        sharedPreferences = getSharedPreferences("VoidOS_Privacy", Context.MODE_PRIVATE);
        // Pehle se hidden apps ko load karna
        hiddenAppsSet = new HashSet<>(sharedPreferences.getStringSet("hidden_packages", new HashSet<String>()));

        PackageManager packageManager = getPackageManager();
        Intent intent = new Intent(Intent.ACTION_MAIN, null);
        intent.addCategory(Intent.CATEGORY_LAUNCHER);
        List<ResolveInfo> appsList = packageManager.queryIntentActivities(intent, 0);

        ListView listView = findViewById(R.id.privacy_apps_list);
        
        // Custom Custom list adapter to show checkboxes inside listview
        ArrayAdapter<ResolveInfo> adapter = new ArrayAdapter<ResolveInfo>(this, android.R.layout.simple_list_item_multiple_choice, appsList) {
            @Override
            public View getView(int position, View convertView, ViewGroup parent) {
                if (convertView == null) {
                    convertView = getLayoutInflater().inflate(android.R.layout.simple_list_item_multiple_choice, parent, false);
                }

                TextView textView = convertView.findViewById(android.R.id.text1);
                textView.setTextColor(0xFFFFFFFF); // White text

                final ResolveInfo info = getItem(position);
                final String packageName = info.activityInfo.packageName;
                
                textView.setText(info.loadLabel(packageManager));

                // Checkbox status dynamic set karna
                ListView lv = (ListView) parent;
                lv.setItemChecked(position, hiddenAppsSet.contains(packageName));

                return convertView;
            }
        };

        listView.setChoiceMode(ListView.CHOICE_MODE_MULTIPLE);
        listView.setAdapter(adapter);

        // Jab user kisi app par click karega, list internally state save karegi
        listView.setOnItemClickListener((parent, view, position, id) -> {
            ResolveInfo info = appsList.get(position);
            String packageName = info.activityInfo.packageName;

            if (listView.isItemChecked(position)) {
                hiddenAppsSet.add(packageName);
            } else {
                hiddenAppsSet.remove(packageName);
            }

            // Database (SharedPreferences) me real-time save karna
            sharedPreferences.edit().putStringSet("hidden_packages", hiddenAppsSet).apply();
        });
    }
}
