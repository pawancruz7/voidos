package com.voidos.launcher;

import android.app.Activity;
import android.content.Intent;
import android.os.Bundle;
import android.view.View;
import android.view.WindowManager;
import android.widget.Button;

public class LockScreenActivity extends Activity {

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        
        // OS level lock screen banane ke liye status bar aur navigation bar ke upar ise show karna hoga
        getWindow().addFlags(WindowManager.LayoutParams.FLAG_SHOW_WHEN_LOCKED
                | WindowManager.LayoutParams.FLAG_DISMISS_KEYGUARD
                | WindowManager.LayoutParams.FLAG_FULLSCREEN);
                
        setContentView(R.layout.activity_lockscreen);

        Button btnUnlock = findViewById(R.id.btn_unlock);
        
        btnUnlock.setOnClickListener(new View.OnClickListener() {
            @Override
            public void onClick(View v) {
                // Unlock hote hi Launcher screen par redirect karna
                Intent intent = new Intent(LockScreenActivity.this, HomeActivity.class);
                startActivity(intent);
                
                // Lock screen ko band karna taaki back press karne par ye wapas na aaye
                finish();
                
                // Clean transition animation
                overridePendingTransition(android.R.anim.fade_in, android.R.anim.fade_out);
            }
        });
    }

    @Override
    public void onBackPressed() {
        // Lock screen par back button daba kar koi bypass na kar sake, isliye ise khali choda hai
    }
}
